"""PostgreSQL implementation of the CUBI knowledge repository.

The SQLite store is the reference implementation of the ``KnowledgeStore``
protocol. This module reuses that verified behaviour and supplies only the
PostgreSQL-specific pieces: DDL (identity columns, PL/pgSQL immutability
triggers), parameter binding and transaction management. One implementation of
the business rules means the two databases cannot drift into two different
definitions of optimistic locking, revision history or audit immutability.

What is genuinely database-level on PostgreSQL:

* ``knowledge_audit`` and ``knowledge_card_event`` reject ``UPDATE``/``DELETE``
  through PL/pgSQL triggers, so append-only history does not depend on the
  application layer.
* ``knowledge_schema_migration`` records every applied version, and the v2→v3
  identity migration runs inside the migration transaction.
* Primary keys, ``UNIQUE`` constraints and foreign keys are enforced by the
  server, including ``PRIMARY KEY(card_id, revision)`` for superseded card
  content and ``PRIMARY KEY(card_id, locale)`` for translations.

Usage::

    store = PostgresKnowledgeStore("postgresql://user@host/db")
    store.close()

A caller-owned ``psycopg`` connection may be passed instead, in which case the
store joins the caller's transaction and never closes it.
"""

