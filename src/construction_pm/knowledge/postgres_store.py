def _convert(sql: str) -> str:
    """Translate the store's portable SQL subset into PostgreSQL syntax."""

    converted = sql.replace("?", "%s")
    if "INSERT OR IGNORE INTO" in converted:
        converted = converted.replace("INSERT OR IGNORE INTO", "INSERT INTO")
        converted = converted.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    return converted


class _Row:
    """Row supporting both column-name and positional access.

    The reference store reads some results by name (``row["revision"]``) and
    unpacks others positionally (``for status, count in rows``). Keeping both
    behaviours lets one implementation serve both drivers.
    """

    __slots__ = ("_names", "_values")

    def __init__(self, names: tuple[str, ...], values: tuple[object, ...]) -> None:
        self._names = names
        self._values = values

    def __getitem__(self, key: object) -> object:
        if isinstance(key, int):
            return self._values[key]
        return self._values[self._names.index(str(key))]

    def keys(self) -> tuple[str, ...]:
        return self._names

    def __iter__(self):
        return iter(self._values)

    def __len__(self) -> int:
        return len(self._values)

    def get(self, key: str, default: object = None) -> object:
        try:
            return self[key]
        except (IndexError, ValueError):
            return default

    def __repr__(self) -> str:
        return f"_Row({dict(zip(self._names, self._values))!r})"


class _Result:
    def __init__(self, cursor, names: tuple[str, ...]) -> None:
        self._cursor = cursor
        self._names = names

    def _row(self, values) -> _Row:
        return _Row(self._names, tuple(values))

    def fetchone(self) -> _Row | None:
        values = self._cursor.fetchone()
        return None if values is None else self._row(values)

    def fetchall(self) -> list[_Row]:
        return [self._row(values) for values in self._cursor.fetchall()]

    def __iter__(self):
        for values in self._cursor:
            yield self._row(values)

    @property
    def rowcount(self) -> int:
        return self._cursor.rowcount


class _Connection:
    """Adapter exposing ``.execute(sql, params)`` over a psycopg connection."""

    def __init__(self, connection) -> None:
        self.raw = connection

    def execute(self, sql: str, parameters: object = ()) -> _Result:
        cursor = self.raw.cursor(row_factory=tuple_row)
        cursor.execute(_convert(sql), tuple(parameters or ()))  # type: ignore[arg-type]
        names = (
            tuple(column.name for column in cursor.description)
            if cursor.description is not None
            else ()
        )
        return _Result(cursor, names)

    def close(self) -> None:
        self.raw.close()


class PostgresKnowledgeStore(SqliteKnowledgeStore):
    """Knowledge repository backed by a real PostgreSQL database."""

    def __init__(self, location, *, migrate: bool = True) -> None:
        if psycopg is None:  # pragma: no cover - driver missing
            raise KnowledgeError("KNOWLEDGE_POSTGRES_DRIVER_UNAVAILABLE")
        if isinstance(location, str):
            if not location.startswith(("postgresql://", "postgres://")):
                raise KnowledgeError("KNOWLEDGE_POSTGRES_DSN_INVALID")
            self._raw = psycopg.connect(location, autocommit=False)
            self._owns_connection = True
        else:
            self._raw = location
            self._owns_connection = False
        self._connection = _Connection(self._raw)
        if migrate:
            self.migrate()

    # -- lifecycle -------------------------------------------------------
    @contextmanager
    def _transaction(self):
        """Join the caller's transaction or run one, nested via savepoints."""

        with self._raw.transaction():
            yield self._connection

    def close(self) -> None:
        if self._owns_connection:
            self._raw.close()

    def migrate(self) -> int:
        from .model import iso, utc_now

        with self._transaction() as connection:
            connection.execute(
                "CREATE TABLE IF NOT EXISTS knowledge_schema_migration "
                "(version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL)"
            )
            row = connection.execute(
                "SELECT MAX(version) FROM knowledge_schema_migration"
            ).fetchone()
            current = 0 if row is None or row[0] is None else int(row[0])
            if current > SCHEMA_VERSION:
                raise KnowledgeError("KNOWLEDGE_SCHEMA_NEWER_THAN_RUNTIME")
            if current < SCHEMA_VERSION:
                for statement in _PG_SCHEMA:
                    connection.execute(statement)
                if current < 3:
                    self._migrate_card_identity(connection)
                connection.execute(
                    "INSERT INTO knowledge_schema_migration(version, applied_at) "
                    "VALUES (?, ?)",
                    (SCHEMA_VERSION, iso(utc_now())),
                )
            return SCHEMA_VERSION

    def _migrate_card_identity(self, connection) -> None:  # type: ignore[override]
        """Rewrite pre-3.0 card identifiers that still embed the card type."""

        from .model import card_id_for

        rows = connection.execute(
            "SELECT card_id, topic_id FROM knowledge_card WHERE topic_id IS NOT NULL"
        ).fetchall()
        # Rewriting a foreign key is a controlled schema migration, not an
        # application edit: suspend the event-immutability triggers for exactly
        # this transaction and restore them before it commits.
        # The card and its translations reference each other while the
        # identifier changes, so the check moves to commit time for this
        # transaction only.
        connection.execute(
            "SET CONSTRAINTS knowledge_card_translation_card_fk DEFERRED"
        )
        connection.execute(
            "ALTER TABLE knowledge_card_event DISABLE TRIGGER USER"
        )
        try:
            for row in rows:
                topic = connection.execute(
                    "SELECT source_id, topic_key FROM knowledge_topic WHERE topic_id=?",
                    (row["topic_id"],),
                ).fetchone()
                if topic is None:
                    continue
                target = card_id_for(str(topic["source_id"]), str(topic["topic_key"]))
                legacy = str(row["card_id"])
                if target == legacy:
                    continue
                occupied = connection.execute(
                    "SELECT 1 FROM knowledge_card WHERE card_id=?", (target,)
                ).fetchone()
                if occupied is not None:
                    continue
                for table in (
                    "knowledge_card_event",
                    "knowledge_card_revision",
                ):
                    connection.execute(
                        f"UPDATE {table} SET card_id=? WHERE card_id=?", (target, legacy)
                    )
                # Translation rows carry a foreign key to the card; move the
                # card first so the key never points at a missing row.
                connection.execute(
                    "UPDATE knowledge_card SET card_id=? WHERE card_id=?", (target, legacy)
                )
                connection.execute(
                    "UPDATE knowledge_card_translation SET card_id=? WHERE card_id=?",
                    (target, legacy),
                )
        finally:
            # Restore the triggers, but never mask the original failure: an
            # aborted transaction rejects every further statement.
            if str(connection.raw.info.transaction_status) != "TransactionStatus.INERROR":
                connection.execute(
                    "ALTER TABLE knowledge_card_event ENABLE TRIGGER USER"
                )

    # -- concurrency hooks -----------------------------------------------
    def _lock_card(self, connection, card_id: str) -> None:
        """Serialize writers for one card for the rest of the transaction.

        An advisory lock covers both races: two writers updating an existing
        revision, and two writers inserting the first revision at once. It is
        released automatically when the transaction ends.
        """

        connection.execute(
            "SELECT pg_advisory_xact_lock(hashtextextended(?, 0))",
            (f"knowledge_card:{card_id}",),
        )

    def _lock_translation(self, connection, card_id: str, locale: str) -> None:
        connection.execute(
            "SELECT pg_advisory_xact_lock(hashtextextended(?, 0))",
            (f"knowledge_translation:{card_id}:{locale}",),
        )

    # -- PostgreSQL-only inspection helpers ------------------------------
    def table_names(self) -> tuple[str, ...]:
        rows = self._connection.execute(
            "SELECT table_name FROM information_schema.tables "
            "WHERE table_schema=current_schema() ORDER BY table_name"
        ).fetchall()
        return tuple(str(row[0]) for row in rows)

    def schema_statements(self) -> tuple[str, ...]:
        return _PG_SCHEMA


