#!/usr/bin/env node
// Generates the assistant registries consumed by the browser bundle.
//
// The browser cannot read `docs/traceability/*.json` or `site/capabilities.mjs`
// at runtime, so both sources are compiled into typed modules here. The
// assistant only ever cites what these files contain: an entry id, the official
// Help topic recorded for it, or the recorded reason why no topic exists.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CAPABILITIES } from "../site/capabilities.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = join(here, "..");
const repoRoot = join(webRoot, "..", "..");

function readRows(file) {
  const document = JSON.parse(
    readFileSync(join(repoRoot, "docs", "traceability", file), "utf8"),
  );
  return document.rows;
}

const rows = [
  ...readRows("engineering-v26.json"),
  ...readRows("enterprise-v26.json"),
];

const helpEntries = rows.map((row) => ({
  id: row.id,
  environment: row.environment,
  kind: row.kind,
  page: row.page ?? "",
  surface: row.surface,
  module: row.module ?? null,
  help: row.help
    ? {
        source: row.help.source,
        title: row.help.title,
        url: row.help.url,
        pdfPage: row.help.pdfPage ?? null,
      }
    : null,
  rationale: row.helpRationale ?? null,
  status: row.status,
}));

const features = CAPABILITIES.map((capability) => ({
  id: capability.id,
  environment: capability.environment,
  route: `/${capability.route}`,
  status: capability.status,
  traceabilityId: capability.traceabilityId,
  ...(capability.routeNote ? { routeNote: capability.routeNote } : {}),
}));

function renderHelp() {
  const lines = [
    "// Generated by scripts/generate-assistant-registries.mjs — do not edit by hand.",
    "// Source: docs/traceability/engineering-v26.json and enterprise-v26.json.",
    "// Regenerate with `node scripts/generate-assistant-registries.mjs` from apps/web.",
    "",
    "export const GENERATED_HELP_ENTRIES = [",
  ];
  for (const entry of helpEntries) {
    lines.push("  {");
    lines.push(`    id: ${JSON.stringify(entry.id)},`);
    lines.push(`    environment: ${JSON.stringify(entry.environment)},`);
    lines.push(`    kind: ${JSON.stringify(entry.kind)},`);
    lines.push(`    page: ${JSON.stringify(entry.page)},`);
    lines.push(`    surface: ${JSON.stringify(entry.surface)},`);
    lines.push(`    module: ${entry.module === null ? "null" : JSON.stringify(entry.module)},`);
    if (entry.help) {
      lines.push("    help: {");
      lines.push(`      source: ${JSON.stringify(entry.help.source)},`);
      lines.push(`      title: ${JSON.stringify(entry.help.title)},`);
      lines.push(`      url: ${JSON.stringify(entry.help.url)},`);
      lines.push(`      pdfPage: ${entry.help.pdfPage === null ? "null" : String(entry.help.pdfPage)},`);
      lines.push("    },");
    } else {
      lines.push("    help: null,");
    }
    lines.push(
      `    rationale: ${entry.rationale === null ? "null" : JSON.stringify(entry.rationale)},`,
    );
    lines.push(`    status: ${JSON.stringify(entry.status)},`);
    lines.push("  },");
  }
  lines.push("] as const;", "");
  return lines.join("\n");
}

function renderFeatures() {
  const lines = [
    "// Generated by scripts/generate-assistant-registries.mjs — do not edit by hand.",
    "// Source: apps/web/site/capabilities.mjs.",
    "// Regenerate with `node scripts/generate-assistant-registries.mjs` from apps/web.",
    "",
    "export const GENERATED_FEATURES = [",
  ];
  for (const feature of features) {
    lines.push("  {");
    lines.push(`    id: ${JSON.stringify(feature.id)},`);
    lines.push(`    environment: ${JSON.stringify(feature.environment)},`);
    lines.push(`    route: ${JSON.stringify(feature.route)},`);
    lines.push(`    status: ${JSON.stringify(feature.status)},`);
    lines.push(`    traceabilityId: ${JSON.stringify(feature.traceabilityId)},`);
    if (feature.routeNote) lines.push(`    routeNote: ${JSON.stringify(feature.routeNote)},`);
    lines.push("  },");
  }
  lines.push("] as const;", "");
  return lines.join("\n");
}

writeFileSync(join(webRoot, "src", "help-registry.generated.ts"), renderHelp(), "utf8");
writeFileSync(join(webRoot, "src", "feature-registry.generated.ts"), renderFeatures(), "utf8");
console.log(
  `Generated ${helpEntries.length} help entries (${helpEntries.filter((entry) => entry.help).length} with an official topic) and ${features.length} features.`,
);
