/** Exact English-to-German/Chinese lookup used by the render helpers. */
export function translateUiString(locale: string, english: string): string | null {
  const base = locale.split("-")[0].toLowerCase();
  if (base !== "de" && base !== "zh") return null;
  const entry = UI_TRANSLATIONS[english];
  if (!entry) return null;
  return base === "de" ? entry[0] : entry[1];
}

