export function isWorkspaceIconName(value: string): value is WorkspaceIconName {
  return (WORKSPACE_ICON_NAMES as readonly string[]).includes(value);
}

/** Render a registered icon. Unknown ids throw instead of silently reusing a glyph. */
export function workspaceIcon(name: WorkspaceIconName): string {
  const path = PATHS[name];
  if (!path) throw new Error(`UNKNOWN_WORKSPACE_ICON:${String(name)}`);
  return `<svg class="cp-icon" data-cp-icon="${name}" viewBox="0 0 16 16" width="16" height="16" aria-hidden="true" focusable="false" fill="none" stroke="currentColor" stroke-width="1.25" stroke-linecap="round" stroke-linejoin="round"><path d="${path}"></path></svg>`;
}
