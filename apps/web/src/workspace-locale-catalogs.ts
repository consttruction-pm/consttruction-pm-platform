export function translateCatalogString(locale: string, english: string): string | null {
  const base = locale.split("-")[0].toLowerCase();
  return INTERFACE_CATALOGS[base]?.[english] ?? null;
}

/** Locales whose command surface is translated by a baseline catalog. */
export function getCatalogLocales(): readonly string[] {
  return Object.keys(INTERFACE_CATALOGS);
}

/** Number of catalog entries, used by the localization coverage report. */
export function catalogSize(locale: string): number {
  return Object.keys(INTERFACE_CATALOGS[locale.split("-")[0].toLowerCase()] ?? {}).length;
}
